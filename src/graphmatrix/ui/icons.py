def _icon_color(kind: str) -> str:
    dark = theme.is_dark() if hasattr(theme, "is_dark") else False
    palette = {
        "project": "#7aa2f7" if dark else "#3b5bdb",
        "workbook": "#e0af68" if dark else "#b8860b",
        "sheet": "#9ece6a" if dark else "#2f7d32",
        "column": "#bb9af7" if dark else "#6a4c93",
        "graph": "#f7768e" if dark else "#c2185b",
    }
    return palette.get(kind, chrome_color())


def chrome_color() -> str:
    """The neutral colour chrome icons are drawn in."""
    dark = theme.is_dark() if hasattr(theme, "is_dark") else False
    return "#c3c8d2" if dark else "#5a6069"


def _render(svg_body: str, color: str, size: int) -> QIcon:
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="{color}" '
        'stroke-linecap="round" stroke-linejoin="round" stroke-width="2" '
        f'viewBox="0 0 24 24">{svg_body}</svg>'
    ).encode()
    renderer = QSvgRenderer(QByteArray(svg))
    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.GlobalColor.transparent)
    from PySide6.QtGui import QPainter

    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()
    return QIcon(pixmap)


def ui_icon(name: str, size: int = 18, color: str | None = None) -> QIcon:
    """A monochrome chrome icon (toolbar, canvas tools, dialogs).

    The icon follows the theme: it is drawn in the current text colour, so it
    stays legible on both the dark and the light presets.
    """
    body = _UI_ICONS.get(name)
    if body is None:
        return QIcon()
    return _render(body, color or chrome_color(), size)


def lucide_icon(name: str, kind: str | None = None, size: int = 16) -> QIcon:
    """Build a QIcon from an embedded Lucide SVG, coloured for the theme."""
    template = _LUCIDE[name]
    color = _icon_color(kind) if kind else chrome_color()
    return _render(template, color, size)
